"""M2 located source dimensions and lowered-board outline in canonical feet."""
import json
from pathlib import Path
from PIL import Image,ImageDraw

ROOT=Path(__file__).resolve().parents[2]
OUT=ROOT/'references/drawing_package'


def main():
    manifest=json.loads((OUT/'manifest.json').read_text())
    reg=json.loads((OUT/'registration.json').read_text())
    cal=json.loads((OUT/'calibration.json').read_text())['calibrated_sheets']
    s4=next(s for s in manifest['sources'] if s['id']=='S04')
    v5=next(v for v in manifest['views'] if v['id']=='S05-V02')
    def F(sheet,x):
        a,b=reg['transformations'][sheet]['grid_x_to_F']
        return a*x+b
    def plan_f(px):
        native=v5['native_box'][0]+px*v5['native_size'][0]/v5['preview_size'][0]
        source=next(s for s in manifest['sources'] if s['id']=='S05')
        return F('S05',native/source['native_size'][0]*1440)
    # Lowered board follows the visible/hidden outline in the inboard profile.
    # This crop is the original native box generated by prepare_m2_sources.py.
    native_box=[6231,2809,9698,4565]
    preview=[2000,1013]
    pivot_px=[1540,606]
    keel_reference_px=[1540,824]
    def native(p):
        return [native_box[0]+p[0]*(native_box[2]-native_box[0])/preview[0],
                native_box[1]+p[1]*(native_box[3]-native_box[1])/preview[1]]
    pin_native=native(pivot_px)
    pin_f=F('S04',pin_native[0]/s4['native_size'][0]*1440)
    from parts import hull
    z0=hull.keel_bottom(pin_f)
    pin_z=z0+(native(keel_reference_px)[1]-pin_native[1])/cal['S04']['native_pixels_per_ft']
    points=[[535,617],[1518,438],[1543,483],[1565,550],[1582,628],[1587,691],
            [1583,730],[1571,778],[1540,820],[1497,855],[1400,886],[1270,916],
            [1120,949],[950,978],[780,997],[620,997],[545,991],[512,985],
            [498,933],[484,860],[475,790],[474,724],[477,673],[482,654],
            [500,650],[514,648]]
    outline=[]
    for p in points:
        n=native(p)
        outline.append([F('S04',n[0]/s4['native_size'][0]*1440),
                        pin_z+(pin_native[1]-n[1])/cal['S04']['native_pixels_per_ft']])
    record=dict(source_views=['S05-V02','S04-V01','S06-V02','S07-V01'],
        source_hashes={s['id']:s['sha256'] for s in manifest['sources'] if s['id'] in ('S04','S05','S06','S07')},
        trunk_outer_aft_ft=plan_f(873),trunk_outer_fore_ft=plan_f(1352),
        trunk_end_length_ft=.5,trunk_gap_ft=4/12,trunk_wall_ft=2/12,
        trunk_course_height_ft=11.5/12,trunk_courses=4,
        board_thickness_ft=2.5/12,
        trunk_basis='Envelope from located plan; 2 x 11.5-in pine walls printed on S07. Gap/board thickness scaled from section; end timber length/course count reconstructed.',
        keelson_aft_width_ft=14/12,keelson_fore_width_ft=16/12,
        keelson_height_above_garboard_ft=10.5/12,
        keelson_lower_foot_ft=.18,
        scarf_fore_ft=F('S05',535),scarf_length_ft=3.5,
        keelson_fore_ft=F('S05',900),keelson_taper_start_ft=F('S05',818),
        keelson_tip_width_ft=.5,mast_fore_support_ft=F('S05',818),
        keelson_basis='Printed widths/depth at garboard and scarf/older-member notes. Located joint limit and taper; 4:1 scarf length, lower seam and inaccessible continuation are construction inferences.',
        board_pivot_FZ=[pin_f,pin_z],board_source_outline_FZ=outline,
        board_source_native_outline=[native(p) for p in points],
        board_source_native_pivot=pin_native,board_keel_reference_native=native(keel_reference_px),
        board_vertical_basis='Same-column source keel/shoe point registered to the corrected M1 keel; retain as-surveyed/straight-keel uncertainty.',
        board_pick_uncertainty_ft=.15,
        board_raised_angle_degrees=-15.0,
        board_pose_note='0 degrees is the traced source lowered outline. The -15-degree raised pose is clearance-limited by actual hatch/deck structure, not a printed historic stop angle; the trial -17-degree pose fouled the main-hatch aft beam.',
        mast_partner_section_ft=[11/12,3.5/12],mast_partner_span_ft=4.2,
        mast_chock_radial_ft=2/12,
        mast_basis='S06 notes 13/14: 2-in pine chocks and 3.5 x 11-in oak partners; span/arrangement scaled, fitted eight-facet count and corner joints inferred.')
    (OUT/'m2_centreline_measurements.json').write_text(json.dumps(record,indent=2)+'\n')
    image=Image.open(ROOT/'renders/m2-board-profile-source.png').convert('RGB')
    draw=ImageDraw.Draw(image)
    draw.line([tuple(p) for p in points]+[tuple(points[0])],fill='#e12b25',width=3)
    x,y=pivot_px
    draw.ellipse((x-10,y-10,x+10,y+10),outline='#0868ac',width=3)
    draw.line((tuple(pivot_px),tuple(keel_reference_px)),fill='#0868ac',width=2)
    image.save(ROOT/'renders/m2-board-trace-source.png')
    print('Trunk outer F:',record['trunk_outer_aft_ft'],record['trunk_outer_fore_ft'])
    print('Board pivot:',record['board_pivot_FZ'],'Scarf forward limit:',record['scarf_fore_ft'])


if __name__=='__main__':
    import sys
    sys.path.insert(0, str(ROOT / 'src'))
    main()
